"""Timestamp-aware sampling shared by preparation, playback, and inference."""
import json
import math
from pathlib import Path


class FrameSampler:
    """Select real frames on a fixed grid; never invent missing motion."""
    def __init__(self, fps=8.0):
        if not math.isfinite(fps) or fps <= 0:
            raise ValueError('sample_fps must be finite and positive')
        self.period = 1.0 / fps
        self.reset()

    def reset(self):
        self.next_time = None
        self.last_time = None
        self.discontinuity = False

    def accept(self, timestamp):
        if not math.isfinite(timestamp):
            raise ValueError('Invalid frame timestamp')
        if timestamp == self.last_time:
            self.discontinuity = False
            return False
        self.discontinuity = (self.last_time is not None and
                              (timestamp <= self.last_time or timestamp - self.last_time > 2.5 * self.period))
        if self.discontinuity:
            self.next_time = None
        self.last_time = timestamp
        if self.next_time is None:
            self.next_time = timestamp + self.period
            return True
        # Small capture jitter must not accidentally halve an approximately 8 Hz stream.
        if timestamp < self.next_time - self.period * .1:
            return False
        self.next_time += self.period
        if self.next_time <= timestamp:
            self.next_time = timestamp + self.period
        return True


def recording_timestamps(video, count, nominal_fps):
    """Prefer original capture timestamps; invalid existing metadata is an error."""
    video = Path(video)
    candidates = [video.with_suffix('.json'),
                  video.parent.parent / 'metadata' / (video.stem + '.json')]
    metadata_path = next((p for p in candidates if p.is_file()), None)
    if metadata_path:
        metadata = json.loads(metadata_path.read_text(encoding='utf-8'))
        stamps = metadata.get('frame_timestamps_seconds')
        if not isinstance(stamps, list) or len(stamps) != count or not stamps:
            raise ValueError(f'Frame/timestamp count mismatch: {metadata_path}')
        if any(not isinstance(t, (int, float)) or not math.isfinite(t) for t in stamps):
            raise ValueError(f'Invalid timestamps: {metadata_path}')
        if stamps[0] < 0 or any(b <= a for a, b in zip(stamps, stamps[1:])):
            raise ValueError(f'Timestamps must increase: {metadata_path}')
        return [t - stamps[0] for t in stamps], metadata
    if not math.isfinite(nominal_fps) or nominal_fps <= 0:
        raise ValueError(f'Video has no usable timing: {video}')
    return [i / nominal_fps for i in range(count)], None


def validate_training_timing(opt):
    """An explicit 8 Hz contract requires a prepared dataset that proves its rate."""
    rate = getattr(opt, 'sample_fps', None)
    if rate is None:
        return  # Legacy frame datasets have unknown timing, not assumed 8 Hz.
    if not math.isfinite(rate) or rate <= 0:
        raise ValueError('--sample_fps must be finite and positive')
    manifest = Path(opt.video_path) / 'sampling.json'
    if not manifest.is_file():
        raise ValueError('Timed training requires sampling.json; use tools/prepare_8fps.py first.')
    timing = json.loads(manifest.read_text(encoding='utf-8'))
    if timing.get('sample_fps') != rate:
        raise ValueError('Dataset sample_fps does not match --sample_fps')
    data = json.loads(Path(opt.annotation_path).read_text(encoding='utf-8'))
    if data.get('sample_fps') != rate or not data.get('annotations_confirmed'):
        raise ValueError('Use reviewed annotations generated by tools/prepare_8fps.py --review')
    groups, source_splits = {}, {}
    pilot = bool(getattr(opt, 'allow_within_session_pilot', False))
    if pilot and (data.get('split_protocol') != 'within_session_trial_pilot'
                  or timing.get('split_protocol') != 'within_session_trial_pilot'):
        raise ValueError('Pilot option requires an explicitly marked within-session pilot dataset')
    for name, item in data['database'].items():
        if name not in timing['clips']:
            raise ValueError(f'Clip missing from sampling manifest: {name}')
        clip = timing['clips'][name]
        if item.get('source_recording_id') != clip['source_recording_id']:
            raise ValueError(f'Clip provenance mismatch: {name}')
        source = clip['source_recording_id']
        if source in source_splits and source_splits[source] != item['subset']:
            raise ValueError('A source recording cannot span splits, including in pilot mode')
        source_splits[source] = item['subset']
        if item.get('split_group_id') != clip['split_group_id']:
            raise ValueError(f'Clip split group mismatch: {name}')
        group = clip.get('session_id', clip['split_group_id'])
        if not pilot and group in groups and groups[group] != item['subset']:
            raise ValueError('A session cannot span training/validation/testing splits')
        groups[group] = item['subset']
    if not {'training', 'validation'} <= {x['subset'] for x in data['database'].values()}:
        raise ValueError('Provide separate training and validation sessions before training')
